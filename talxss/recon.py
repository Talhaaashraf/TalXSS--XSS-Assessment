"""Recon for TalXSS — the professional pentester's FIRST moves against a target.

Before touching parameters, a real assessor fingerprints the stack, reads the
security headers, and — critically — works out whether a **WAF/firewall** sits
in front of the app, because that changes how (and how fast) you test.

Everything here is passive or uses a single benign, malicious-*looking* probe.
Nothing destructive, nothing that bypasses or evades a WAF — the goal is to
*detect and report* the WAF and then be polite, exactly as a legitimate
engagement would. Authorization + scope are enforced by the caller.

Functions return plain dicts (Finding-shaped) so `scanner.py` can wrap them in
its `Finding` type without a circular import.
"""

from __future__ import annotations

from dataclasses import dataclass, field, asdict

# --------------------------------------------------------------------------- #
# WAF fingerprint signatures: (vendor, where, needle)
#   where ∈ {header-name, "server", "cookie", "body"}
# --------------------------------------------------------------------------- #
_WAF_SIGS: list[tuple[str, str, str]] = [
    ("Cloudflare", "cf-ray", ""),
    ("Cloudflare", "server", "cloudflare"),
    ("Cloudflare", "cookie", "__cfduid"),
    ("Cloudflare", "cookie", "cf_clearance"),
    ("AWS CloudFront/WAF", "x-amz-cf-id", ""),
    ("AWS CloudFront/WAF", "x-amzn-requestid", ""),
    ("AWS CloudFront/WAF", "server", "awselb"),
    ("Akamai", "x-akamai-transformed", ""),
    ("Akamai", "server", "akamaighost"),
    ("Imperva/Incapsula", "x-iinfo", ""),
    ("Imperva/Incapsula", "cookie", "incap_ses"),
    ("Imperva/Incapsula", "cookie", "visid_incap"),
    ("Sucuri", "x-sucuri-id", ""),
    ("Sucuri", "server", "sucuri"),
    ("F5 BIG-IP ASM", "cookie", "ts"),
    ("F5 BIG-IP", "cookie", "bigipserver"),
    ("ModSecurity", "server", "mod_security"),
    ("ModSecurity", "server", "modsecurity"),
    ("Barracuda", "cookie", "barra_counter_session"),
    ("Wordfence", "body", "generated by wordfence"),
    ("DotDefender", "body", "dotdefender blocked your request"),
    ("FortiWeb", "cookie", "fortiwafsid"),
    ("Citrix NetScaler", "cookie", "ns_af"),
    ("Citrix NetScaler", "cookie", "citrix_ns_id"),
]

# Markers that typically appear on a WAF block page.
_BLOCK_MARKERS = [
    "attention required", "request blocked", "access denied", "forbidden",
    "has been blocked", "security policy", "not acceptable", "web application firewall",
    "your request was blocked", "incident id", "reference #", "ray id",
]

_BENIGN_PROBES = {
    "talxss_waf_x": "<script>alert(1)</script>",
    "talxss_waf_y": "../../../../etc/passwd",
}


@dataclass
class WafProfile:
    present: bool = False
    name: str = "unknown"
    confidence: str = "none"      # none | low | medium | high
    blocking: bool = False        # did it actively block our benign probe?
    evidence: list[str] = field(default_factory=list)

    def as_dict(self) -> dict:
        return asdict(self)


def _headers_lower(resp) -> dict:
    return {k.lower(): str(v) for k, v in resp.headers.items()}


def _cookie_names(resp) -> list[str]:
    names = [c.name.lower() for c in getattr(resp, "cookies", [])]
    # Fall back to raw Set-Cookie header if cookies weren't parsed.
    sc = resp.headers.get("Set-Cookie", "")
    if sc:
        names.append(sc.lower())
    return names


def fingerprint(resp) -> dict:
    """Server / technology hints from response headers."""
    h = _headers_lower(resp)
    info = {
        "status": getattr(resp, "status_code", None),
        "server": h.get("server", ""),
        "x_powered_by": h.get("x-powered-by", ""),
        "via": h.get("via", ""),
        "content_type": h.get("content-type", ""),
    }
    return {k: v for k, v in info.items() if v not in ("", None)}


def _finding(name: str, severity: str, note: str, evidence: str = "",
             url: str = "") -> dict:
    """Build a Finding-shaped dict (keys match scanner.Finding fields)."""
    return dict(url=url, method="GET", parameter="-", context="recon",
                payload_name=name, payload="", severity=severity,
                evidence=evidence, note=note, attack_type="security-header")


def security_headers(resp, url: str = "") -> list[dict]:
    """Flag missing/weak security headers and insecure cookie flags."""
    h = _headers_lower(resp)
    out: list[dict] = []

    def missing(header: str, sev: str, advice: str):
        if header not in h:
            out.append(_finding(f"missing:{header}", sev,
                                 f"Response is missing the `{header}` header. {advice}",
                                 url=url))

    missing("content-security-policy", "medium",
            "A strict CSP is the strongest defense-in-depth against XSS.")
    missing("strict-transport-security", "low",
            "HSTS forces HTTPS and blocks SSL-stripping.")
    missing("x-frame-options", "low",
            "Without it (and no CSP frame-ancestors) the page can be framed → clickjacking.")
    missing("x-content-type-options", "low",
            "Set `nosniff` to stop MIME-type sniffing.")
    missing("referrer-policy", "low", "Controls how much referrer data leaks cross-site.")

    # Weak CSP (present but permissive).
    csp = h.get("content-security-policy", "")
    if csp and ("unsafe-inline" in csp or "unsafe-eval" in csp or "*" in csp):
        out.append(_finding("weak:content-security-policy", "medium",
                            "CSP present but permissive (unsafe-inline/unsafe-eval/wildcard) "
                            "— offers little XSS protection.",
                            evidence=csp[:160], url=url))

    # Cookie flags.
    for c in getattr(resp, "cookies", []):
        rest = {k.lower(): v for k, v in getattr(c, "_rest", {}).items()}
        problems = []
        if not c.secure:
            problems.append("Secure")
        if "httponly" not in rest:
            problems.append("HttpOnly")
        if "samesite" not in rest:
            problems.append("SameSite")
        if problems:
            out.append(_finding(f"cookie:{c.name}", "low",
                                f"Cookie `{c.name}` is missing flags: {', '.join(problems)}. "
                                "Missing HttpOnly lets injected JS read it.",
                                url=url))
    return out


def detect_waf(request_fn, base_url: str, baseline_resp, logger=None) -> WafProfile:
    """Fingerprint a WAF passively, then confirm with one benign behavioural probe.

    `request_fn(method, url, params=...)` is the scanner's polite HTTP wrapper
    (keeps the delay + request counter). `baseline_resp` is a normal GET already
    made against `base_url`.
    """
    log = logger or (lambda m: None)
    prof = WafProfile()

    # ---- passive: headers / cookies / body of the baseline response ----
    h = _headers_lower(baseline_resp)
    cookies = _cookie_names(baseline_resp)
    body = (getattr(baseline_resp, "text", "") or "")[:4000].lower()
    for vendor, where, needle in _WAF_SIGS:
        hit = False
        if where == "server":
            hit = needle in h.get("server", "")
        elif where == "cookie":
            hit = any(needle in c for c in cookies)
        elif where == "body":
            hit = needle in body
        else:  # a specific header name must simply be present (or contain needle)
            val = h.get(where)
            hit = val is not None and (needle == "" or needle in val)
        if hit:
            prof.present = True
            prof.name = vendor
            prof.confidence = "high"
            prof.evidence.append(f"signature: {vendor} via {where}"
                                 + (f"~{needle}" if needle else ""))

    # ---- behavioural: does a benign malicious-looking probe get blocked? ----
    try:
        probe = request_fn("GET", base_url, params=_BENIGN_PROBES)
        base_status = getattr(baseline_resp, "status_code", 200)
        probe_status = getattr(probe, "status_code", 200)
        pbody = (getattr(probe, "text", "") or "").lower()
        blocked = (
            probe_status in (403, 406, 429, 501, 999)
            and probe_status != base_status
        ) or any(m in pbody for m in _BLOCK_MARKERS)
        if blocked:
            prof.present = True
            prof.blocking = True
            if prof.confidence in ("none", "low"):
                prof.confidence = "medium"
            prof.evidence.append(
                f"benign probe blocked (HTTP {probe_status}"
                + (" + block-page markers" if any(m in pbody for m in _BLOCK_MARKERS) else "")
                + ")")
    except Exception as e:  # noqa: BLE001 - behavioural probe is best-effort
        prof.evidence.append(f"probe error: {type(e).__name__}")

    if prof.present:
        log(f"[waf] detected: {prof.name} (confidence={prof.confidence}, "
            f"blocking={prof.blocking})")
    else:
        log("[waf] no WAF/firewall fingerprinted on the baseline response")
    return prof
